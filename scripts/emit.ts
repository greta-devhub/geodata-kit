/**
 * Turns the canonical JSON under data/ into what each package ships:
 *
 *   packages/geodata-kit/data/**.mjs       lazily loaded modules (cities, deep subdivisions, airports, shapes)
 *   packages/geodata-kit/src/loaders.generated.js (+ .d.ts)
 *                                          literal import() map so bundlers can split per country
 *   packages/geodata-kit-localities/data/  gzip shards (copied)
 *   packages/geodata-kit-postal/data/      gzip shards (copied)
 *   packages/geodata-kit-tz/data/          binary timezone index (copied)
 *   python/src/geodata_kit/data/           JSON for the Python package (copied)
 *
 * Core data (countries, names, groups, languages, …) is imported as JSON by the
 * sources and bundled by tsup, so it is not emitted here.
 */
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

import { compareStrings, ensureDir } from './lib/io.js';
import { dataPath, ROOT } from './lib/paths.js';

const MAIN = join(ROOT, 'packages', 'geodata-kit');
const MAIN_DATA = join(MAIN, 'data');

/** `export default JSON.parse("…")`: parses faster than an object literal and keeps the text verbatim. */
function writeModule(target: string, jsonPath: string): void {
  const text = readFileSync(jsonPath, 'utf8').trim();
  writeFileSync(target, `export default JSON.parse(${JSON.stringify(text)});\n`);
}

function emitDirectory(source: string, target: string): string[] {
  ensureDir(target);
  const written: string[] = [];
  for (const file of readdirSync(source).sort(compareStrings)) {
    const path = join(source, file);
    if (statSync(path).isDirectory()) {
      written.push(...emitDirectory(path, join(target, file)).map((name) => `${file}/${name}`));
    } else if (file.endsWith('.json')) {
      const name = `${basename(file, '.json')}.mjs`;
      writeModule(join(target, name), path);
      written.push(name);
    }
  }
  return written;
}

function main(): void {
  rmSync(MAIN_DATA, { recursive: true, force: true });
  ensureDir(MAIN_DATA);
  const lines: string[] = [
    '// Generated by scripts/emit.ts. Do not edit by hand.',
    '// Literal import() paths so bundlers can split the data per country.',
    '',
  ];
  const declarations: string[] = [
    '// Generated by scripts/emit.ts. Do not edit by hand.',
    'type Loader = () => Promise<{ default: unknown }>;',
  ];

  // Deep subdivisions: one module per country.
  if (existsSync(dataPath('subdivisions', 'deep'))) {
    const files = emitDirectory(dataPath('subdivisions', 'deep'), join(MAIN_DATA, 'subdivisions'));
    lines.push('export const SUBDIVISION_LOADERS = {');
    for (const file of files) lines.push(`  ${basename(file, '.mjs')}: () => import('../data/subdivisions/${file}'),`);
    lines.push('};', '');
    declarations.push('export declare const SUBDIVISION_LOADERS: Record<string, Loader>;');
  }

  // Cities: one module per country and tier band.
  if (existsSync(dataPath('cities'))) {
    const target = join(MAIN_DATA, 'cities');
    ensureDir(target);
    lines.push('export const CITY_LOADERS = {');
    for (const country of readdirSync(dataPath('cities')).filter((name) => /^[A-Z]{2}$/.test(name)).sort(compareStrings)) {
      const bands = emitDirectory(dataPath('cities', country), join(target, country));
      const entries = bands.map((file) => `${basename(file, '.mjs')}: () => import('../data/cities/${country}/${file}')`);
      lines.push(`  ${country}: { ${entries.join(', ')} },`);
    }
    lines.push('};', '');
    for (const file of readdirSync(dataPath('cities')).filter((name) => name.endsWith('.json'))) {
      writeModule(join(target, `${basename(file, '.json')}.mjs`), dataPath('cities', file));
      const exportName = `load${basename(file, '.json').replace(/(^|-)(\w)/g, (_: string, __: string, letter: string) => letter.toUpperCase())}`;
      lines.push(`export const ${exportName} = () => import('../data/cities/${basename(file, '.json')}.mjs');`);
      declarations.push(`export declare const ${exportName}: Loader;`);
    }
    lines.push('');
    declarations.push('export declare const CITY_LOADERS: Record<string, Record<string, Loader>>;');
  }

  // Single-file datasets.
  for (const [name, file] of [['Airports', 'airports.json'], ['CountryShapes', 'shapes/countries.json'], ['SubdivisionShapes', 'shapes/subdivisions.json']] as const) {
    if (!existsSync(dataPath(file))) continue;
    const moduleName = file.replace(/\.json$/, '.mjs');
    ensureDir(join(MAIN_DATA, moduleName.split('/').slice(0, -1).join('/')));
    writeModule(join(MAIN_DATA, moduleName), dataPath(file));
    lines.push(`export const load${name} = () => import('../data/${moduleName}');`);
    declarations.push(`export declare const load${name}: Loader;`);
  }

  writeFileSync(join(MAIN, 'src', 'loaders.generated.js'), `${lines.join('\n')}\n`);
  writeFileSync(join(MAIN, 'src', 'loaders.generated.d.ts'), `${declarations.join('\n')}\n`);

  // Optional packages: copy their shards.
  for (const [source, target] of [
    ['localities', join(ROOT, 'packages', 'geodata-kit-localities', 'data')],
    ['postal', join(ROOT, 'packages', 'geodata-kit-postal', 'data')],
    ['tz', join(ROOT, 'packages', 'geodata-kit-tz', 'data')],
  ] as const) {
    if (!existsSync(dataPath(source))) continue;
    rmSync(target, { recursive: true, force: true });
    cpSync(dataPath(source), target, { recursive: true });
  }

  // Python: same JSON (localities/postal/tz go to their own Python data packages).
  const pythonData = join(ROOT, 'python', 'src', 'geodata_kit', 'data');
  rmSync(pythonData, { recursive: true, force: true });
  for (const part of ['core', 'subdivisions', 'cities', 'address', 'phone', 'shapes', 'airports.json']) {
    if (existsSync(dataPath(part))) cpSync(dataPath(part), join(pythonData, part), { recursive: true });
  }
  for (const [part, pkg] of [['localities', 'geodata_kit_localities'], ['postal', 'geodata_kit_postal']] as const) {
    const target = join(ROOT, 'python', 'extras', pkg, 'src', pkg, 'data');
    if (!existsSync(dataPath(part))) continue;
    rmSync(target, { recursive: true, force: true });
    cpSync(dataPath(part), target, { recursive: true });
  }
  console.log('Emitted package data.');
}

main();
