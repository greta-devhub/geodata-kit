/**
 * Turns the canonical JSON under data/ into what each package ships:
 *
 *   packages/geodata-kit-subdivisions/data/{CC}.mjs        levels 2–4 per country
 *   packages/geodata-kit-cities/data/{CC}/{band}.mjs       cities per country and tier band, plus index.mjs
 *   packages/geodata-kit-airports/data/airports.mjs
 *   packages/geodata-kit-shapes/data/{countries,subdivisions}.mjs
 *   packages/<each of these>/src/loaders.generated.js (+ .d.ts)
 *                                          literal import() map so bundlers can split the data
 *   packages/geodata-kit-{localities,postal,tz}/data/      gzip shards / binary index (copied)
 *   python/src/geodata_kit/data/           JSON for the Python package (copied)
 *
 * Small datasets (core, level-1 subdivisions, address formats, phone metadata)
 * are imported as JSON by the sources and bundled by tsup, so they are not
 * emitted here.
 */
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

import { compareStrings, ensureDir } from './lib/io.js';
import { dataPath, ROOT } from './lib/paths.js';

const packageDir = (name: string): string => join(ROOT, 'packages', name);

/** `export default JSON.parse("…")`: parses faster than an object literal and keeps the text verbatim. */
function writeModule(target: string, jsonPath: string): void {
  const text = readFileSync(jsonPath, 'utf8').trim();
  writeFileSync(target, `export default JSON.parse(${JSON.stringify(text)});\n`);
}

function emitDirectory(source: string, target: string): string[] {
  ensureDir(target);
  const written: string[] = [];
  for (const file of readdirSync(source).sort(compareStrings)) {
    const path = join(source, file);
    if (statSync(path).isDirectory()) {
      written.push(...emitDirectory(path, join(target, file)).map((name) => `${file}/${name}`));
    } else if (file.endsWith('.json')) {
      const name = `${basename(file, '.json')}.mjs`;
      writeModule(join(target, name), path);
      written.push(name);
    }
  }
  return written;
}

/** Writes src/loaders.generated.js and .d.ts of a package. */
function writeLoaders(pkg: string, lines: string[], declarations: string[]): void {
  const banner = '// Generated by scripts/emit.ts. Do not edit by hand.';
  writeFileSync(join(packageDir(pkg), 'src', 'loaders.generated.js'), [banner, '// Literal import() paths so bundlers can split the data.', '', ...lines, ''].join('\n'));
  writeFileSync(join(packageDir(pkg), 'src', 'loaders.generated.d.ts'), [banner, 'type Loader = () => Promise<{ default: unknown }>;', ...declarations, ''].join('\n'));
}

function freshDataDir(pkg: string): string {
  const dir = join(packageDir(pkg), 'data');
  rmSync(dir, { recursive: true, force: true });
  ensureDir(dir);
  return dir;
}

function main(): void {
  // Subdivisions: one module per country with levels 2–4.
  {
    const dir = freshDataDir('geodata-kit-subdivisions');
    const files = emitDirectory(dataPath('subdivisions', 'deep'), dir);
    writeLoaders('geodata-kit-subdivisions',
      ['export const SUBDIVISION_LOADERS = {', ...files.map((file) => `  ${basename(file, '.mjs')}: () => import('../data/${file}'),`), '};'],
      ['export declare const SUBDIVISION_LOADERS: Record<string, Loader>;']);
  }

  // Cities: one module per country and tier band, plus the id index.
  {
    const dir = freshDataDir('geodata-kit-cities');
    const lines = ['export const CITY_LOADERS = {'];
    for (const country of readdirSync(dataPath('cities')).filter((name) => /^[A-Z]{2}$/.test(name)).sort(compareStrings)) {
      const bands = emitDirectory(dataPath('cities', country), join(dir, country));
      lines.push(`  ${country}: { ${bands.map((file) => `${basename(file, '.mjs')}: () => import('../data/${country}/${file}')`).join(', ')} },`);
    }
    writeModule(join(dir, 'index.mjs'), dataPath('cities', 'index.json'));
    lines.push('};', '', "export const loadIndex = () => import('../data/index.mjs');");
    writeLoaders('geodata-kit-cities', lines,
      ['export declare const CITY_LOADERS: Record<string, Record<string, Loader>>;', 'export declare const loadIndex: Loader;']);
  }

  // Airports: one module.
  {
    const dir = freshDataDir('geodata-kit-airports');
    writeModule(join(dir, 'airports.mjs'), dataPath('airports.json'));
    writeLoaders('geodata-kit-airports', ["export const loadAirports = () => import('../data/airports.mjs');"], ['export declare const loadAirports: Loader;']);
  }

  // Shapes: countries and first-level subdivisions.
  {
    const dir = freshDataDir('geodata-kit-shapes');
    writeModule(join(dir, 'countries.mjs'), dataPath('shapes', 'countries.json'));
    writeModule(join(dir, 'subdivisions.mjs'), dataPath('shapes', 'subdivisions.json'));
    writeLoaders('geodata-kit-shapes',
      ["export const loadCountryShapes = () => import('../data/countries.mjs');", "export const loadSubdivisionShapes = () => import('../data/subdivisions.mjs');"],
      ['export declare const loadCountryShapes: Loader;', 'export declare const loadSubdivisionShapes: Loader;']);
  }

  // Optional packages: copy their shards.
  for (const [source, target] of [
    ['localities', join(packageDir('geodata-kit-localities'), 'data')],
    ['postal', join(packageDir('geodata-kit-postal'), 'data')],
    ['tz', join(packageDir('geodata-kit-tz'), 'data')],
  ] as const) {
    if (!existsSync(dataPath(source))) continue;
    rmSync(target, { recursive: true, force: true });
    cpSync(dataPath(source), target, { recursive: true });
  }

  // Python: same JSON (localities/postal/tz go to their own Python data packages).
  const pythonData = join(ROOT, 'python', 'src', 'geodata_kit', 'data');
  rmSync(pythonData, { recursive: true, force: true });
  for (const part of ['core', 'subdivisions', 'cities', 'address', 'phone', 'shapes', 'airports.json']) {
    if (existsSync(dataPath(part))) cpSync(dataPath(part), join(pythonData, part), { recursive: true });
  }
  for (const [part, pkg] of [['localities', 'geodata_kit_localities'], ['postal', 'geodata_kit_postal']] as const) {
    const target = join(ROOT, 'python', 'extras', pkg, 'src', pkg, 'data');
    if (!existsSync(dataPath(part))) continue;
    rmSync(target, { recursive: true, force: true });
    cpSync(dataPath(part), target, { recursive: true });
  }
  console.log('Emitted package data.');
}

main();
